export function getProjectsCopy(locale: "zh-CN" | "en-US") {
  return locale === "zh-CN" ? zhCN : enUS;
}

export function projectRootKindLabel(
  locale: "zh-CN" | "en-US",
  kind: ProjectRootKind
): string {
  const copy = getProjectsCopy(locale);
  return kind === "git-repository" ? copy.gitRepository : copy.directory;
}

export function projectRootRoleLabel(
  locale: "zh-CN" | "en-US",
  role: ProjectRootRole
): string {
  const copy = getProjectsCopy(locale);
  const labels: Record<ProjectRootRole, string> = {
    "primary-source": copy.primarySource,
    "supporting-source": copy.supportingSource,
    documentation: copy.documentation,
    knowledge: copy.knowledge,
    assets: copy.assets
  };
  return labels[role];
}

export function projectRootAccessLabel(
  locale: "zh-CN" | "en-US",
  access: ProjectRootAccess
): string {
  const copy = getProjectsCopy(locale);
  return access === "read-write" ? copy.readWrite : copy.readOnly;
}
